# A variable is a name that stores a value.
# The = sign assigns the value on the right to the name on the left.
# Here, height stores the integer (whole number) 10.
height = 10

# This creates another variable named width and assigns it the integer 5.
width = 5

# The * operator multiplies values.
# Python replaces height and width with their stored values, so this means
# 10 * 5. The result, 50, is assigned to the variable named area.
area = height * width

# print() is a built-in Python function that displays information in the
# console. Parentheses contain the values passed to the function.
# Text inside quotation marks is a string. Commas separate multiple values,
# and print() places spaces between those values in the output.
print("The area of a rectangle with height", height, "and width", width, "is", area)
